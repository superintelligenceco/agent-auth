// Generates the CLI and REST API reference pages from src/cli.ts and openapi.yaml, so the docs
// always match what the tool prints and what the server exposes.
import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";

const root = new URL("../", import.meta.url);
const header = (source) =>
  `<!-- Generated by docs/gen-reference.mjs from ${source}. Do not edit by hand. -->\n\n`;

// CLI reference: the help text is the HELP template literal in src/cli.ts.
const cli = readFileSync(new URL("src/cli.ts", root), "utf8");
const help = cli.match(/const HELP = `([\s\S]*?)`;/)?.[1];
if (!help) throw new Error("HELP not found in src/cli.ts");
writeFileSync(
  new URL("reference/cli.md", import.meta.url),
  `${header("src/cli.ts")}# CLI reference

The \`agent-auth\` command runs the server and talks to it. Every command reads its settings from
flags or from the environment variables listed below. This page shows the output of
\`agent-auth --help\`.

\`\`\`text
${help.trim()}
\`\`\`

## Exit codes

| Code | Meaning |
| --- | --- |
| \`0\` | Success, or the request is allowed |
| \`1\` | Error, including usage errors and a tampered audit chain |
| \`3\` | The request is denied, or the token is inactive |
| \`4\` | The request needs a human approval |
`,
);

// REST API reference: one section per operation in openapi.yaml.
const spec = parse(readFileSync(new URL("openapi.yaml", root), "utf8"));
// Tags say who calls an operation: principals use the admin token, agents their agent token.
function auth(op) {
  const tags = op.tags ?? [];
  if (tags.includes("agent") && tags.includes("principal")) return "token or admin";
  if (tags.includes("principal")) return "admin";
  if (tags.includes("agent")) return "token";
  return "none";
}
const resolve = (r) => (r.$ref ? spec.components.responses[r.$ref.split("/").pop()] : r);
const rows = [];
const sections = [];
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    const m = method.toUpperCase();
    rows.push(`| \`${m} ${path}\` | ${auth(op)} | ${op.summary} |`);
    const codes = Object.entries(op.responses ?? {})
      .map(([code, r]) => `- \`${code}\`: ${resolve(r).description ?? ""}`.trim())
      .join("\n");
    sections.push(
      `### ${op.summary}\n\n\`${m} ${path}\` (operation \`${op.operationId}\`)\n\n${op.description ? `${op.description.trim()}\n\n` : ""}Responses:\n\n${codes}\n`,
    );
  }
}
writeFileSync(
  new URL("reference/api.md", import.meta.url),
  `${header("openapi.yaml")}# REST API reference

${spec.info.description.trim()}

The full OpenAPI 3.1 description is
[openapi.yaml](https://github.com/superintelligenceco/agent-auth/blob/main/openapi.yaml). A test keeps
it in sync with the routes the server exposes.

| Method and path | Auth | Purpose |
| --- | --- | --- |
${rows.join("\n")}

## Operations

${sections.join("\n")}`,
);
console.log("wrote reference/cli.md and reference/api.md");
